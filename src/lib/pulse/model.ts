// src/lib/pulse/model.ts
// Pure Pulse logic (spec 6.3-6.11): workloads, KPIs, issues and trigger
// matching. Health comes from the Rust triage verdicts; nothing here
// re-derives it.
import type { Verdict } from '../utils/health';

export type WorkloadKind = 'deployment' | 'statefulset' | 'daemonset' | 'job';
export type ObjectKind = WorkloadKind | 'node';

/** Short kind prefixes as kubectl prints them. */
export const KIND_SHORT: Record<ObjectKind, string> = {
  deployment: 'deploy',
  statefulset: 'sts',
  daemonset: 'ds',
  job: 'job',
  node: 'node',
};

export interface PulseObject {
  kind: ObjectKind;
  name: string;
  namespace: string | null;
  verdict: Verdict;
  /** e.g. "0/3" ready, for the impact line. */
  ready?: string;
  /** spec.replicas, for Scale (Deployments and StatefulSets). */
  desired?: number;
}

export const objectKey = (o: { kind: ObjectKind; name: string; namespace: string | null }) =>
  `${o.kind}/${o.namespace ?? ''}/${o.name}`;

// ---------- KPIs ----------

export interface Kpis {
  total: number;
  healthy: number;
  warning: number;
  critical: number;
  /** healthy / total * 100, or null with no workloads. */
  healthPct: number | null;
}

/** Counts per verdict status. Unknown counts toward the total only. */
export function computeKpis(workloads: readonly Pick<PulseObject, 'verdict'>[]): Kpis {
  let healthy = 0;
  let warning = 0;
  let critical = 0;
  for (const w of workloads) {
    if (w.verdict.status === 'ok') healthy++;
    else if (w.verdict.status === 'warn') warning++;
    else if (w.verdict.status === 'fail') critical++;
  }
  const total = workloads.length;
  return { total, healthy, warning, critical, healthPct: total ? (healthy / total) * 100 : null };
}

/** API reachability over the session, as a percentage of polls that answered. */
export function reachabilityPct(ok: number, total: number): number | null {
  return total > 0 ? (ok / total) * 100 : null;
}

// ---------- Issues ----------

export type Sev = 'crit' | 'err' | 'warn';
export const SEV_RANK: Record<Sev, number> = { crit: 0, err: 1, warn: 2 };
export const SEV_LABEL: Record<Sev, string> = { crit: 'Critical', err: 'Error', warn: 'Warning' };

export interface Issue {
  id: string;
  kind: ObjectKind;
  name: string;
  namespace: string | null;
  sev: Sev;
  reason: string;
  verdict: Verdict;
  /** Epoch ms the problem started (verdict `since`, else first seen in-app). */
  startedAt: number;
  ready?: string;
  desired?: number;
}

export function sevOf(v: Verdict): Sev | null {
  if (v.status === 'ok' || v.status === 'unknown') return null;
  if (v.severity === 'critical') return 'crit';
  if (v.severity === 'error') return 'err';
  if (v.severity === 'warning') return 'warn';
  return v.status === 'fail' ? 'err' : 'warn';
}

/**
 * Problems first: severity, then the newest start. `firstSeen` supplies a
 * start time when the verdict carries no `since`.
 */
export function buildIssues(objects: readonly PulseObject[], firstSeen: (key: string) => number): Issue[] {
  const out: Issue[] = [];
  for (const o of objects) {
    const sev = sevOf(o.verdict);
    if (!sev) continue;
    const key = objectKey(o);
    const parsed = o.verdict.since ? Date.parse(o.verdict.since) : NaN;
    out.push({
      id: key,
      kind: o.kind,
      name: o.name,
      namespace: o.namespace,
      sev,
      reason: o.verdict.reason || (sev === 'warn' ? 'Degraded' : 'Failing'),
      verdict: o.verdict,
      startedAt: Number.isFinite(parsed) ? parsed : firstSeen(key),
      ready: o.ready,
      desired: o.desired,
    });
  }
  return out.sort((a, b) => SEV_RANK[a.sev] - SEV_RANK[b.sev] || b.startedAt - a.startedAt || a.id.localeCompare(b.id));
}

// ---------- Affected pods and evidence ----------

interface PodLike {
  name: string;
  namespace: string;
  node: string | null;
  verdict: Verdict;
}

/** The suffix each controller appends to its pod names. */
const POD_SUFFIX: Record<WorkloadKind, RegExp> = {
  deployment: /^[a-z0-9]{6,10}-[a-z0-9]{5}$/, // <rs-hash>-<pod>
  statefulset: /^\d+$/, // <ordinal>
  daemonset: /^[a-z0-9]{5}$/,
  job: /^[a-z0-9]{5}$/,
};

/**
 * Whether a pod name was generated by this workload. PodInfo has no owner
 * reference, so this follows the controller naming scheme exactly, which
 * keeps `checkout` from claiming `checkout-api`'s pods.
 */
export function ownsPodName(kind: WorkloadKind, owner: string, podName: string): boolean {
  if (!podName.startsWith(`${owner}-`)) return false;
  return POD_SUFFIX[kind].test(podName.slice(owner.length + 1));
}

/** Pods that belong to an issue: by naming scheme for workloads, by node for nodes. */
export function podsFor<P extends PodLike>(issue: Pick<Issue, 'kind' | 'name' | 'namespace'>, pods: readonly P[]): P[] {
  const kind = issue.kind;
  if (kind === 'node') return pods.filter((p) => p.node === issue.name);
  return pods.filter((p) => p.namespace === issue.namespace && ownsPodName(kind, issue.name, p.name));
}

interface EventLike {
  namespace: string;
  type: string;
  involved_object: string;
  involved_kind: string;
}

export function eventsFor<E extends EventLike>(issue: Pick<Issue, 'kind' | 'name' | 'namespace'>, events: readonly E[]): E[] {
  return events.filter((e) => {
    if (e.type !== 'Warning') return false;
    if (issue.kind === 'node') return e.involved_kind === 'Node' && e.involved_object === issue.name;
    const kind = issue.kind as WorkloadKind;
    return e.namespace === issue.namespace && (e.involved_object === issue.name || ownsPodName(kind, issue.name, e.involved_object));
  });
}

// ---------- Trigger matching (spec 6.11) ----------

export type ActivityKind = 'rollout' | 'scale' | 'restart' | 'node' | 'warning' | 'action';

export interface ActivityItem {
  id: string;
  t: number;
  kind: ActivityKind;
  /** Tone of the icon: problems are coloured, changes neutral. */
  tone: 'bad' | 'warn' | 'neutral' | 'apex';
  objectKind: ObjectKind | 'pod' | 'replicaset' | 'event';
  /** Workload or node the change is about (owner for pods and ReplicaSets). */
  target: { kind: ObjectKind; name: string; namespace: string | null } | null;
  text: string;
  detail: string;
  by?: string;
}

export const TRIGGER_WINDOW_MS = 15 * 60 * 1000;

/** Kinds that can cause an issue. Restarts and Warning events are symptoms. */
const CAUSES: ReadonlySet<ActivityKind> = new Set(['rollout', 'scale', 'node', 'action']);

export interface Trigger {
  item: ActivityItem;
  /** How long after the change the issue started, ms (>= 0). */
  afterMs: number;
}

/**
 * The latest change in the 15 minutes before the issue started: same object
 * first; for workloads, also a change to a node that runs their pods.
 */
export function findTrigger(
  issue: Pick<Issue, 'kind' | 'name' | 'namespace' | 'startedAt'>,
  activity: readonly ActivityItem[],
  nodesOfIssue: readonly string[] = [],
  windowMs = TRIGGER_WINDOW_MS
): Trigger | null {
  const from = issue.startedAt - windowMs;
  let best: ActivityItem | null = null;
  let bestRank = Infinity;
  for (const a of activity) {
    if (!CAUSES.has(a.kind) || !a.target) continue;
    if (a.t < from || a.t > issue.startedAt) continue;
    let rank: number;
    if (a.target.kind === issue.kind && a.target.name === issue.name && a.target.namespace === issue.namespace) rank = 0;
    else if (issue.kind !== 'node' && a.target.kind === 'node' && nodesOfIssue.includes(a.target.name)) rank = 1;
    else continue;
    if (rank < bestRank || (rank === bestRank && best && a.t > best.t)) {
      best = a;
      bestRank = rank;
    }
  }
  return best ? { item: best, afterMs: issue.startedAt - best.t } : null;
}

// ---------- Formatting ----------

/** "now", "45s", "14m", "3h", "2d". */
export function shortDuration(ms: number): string {
  const s = Math.max(0, Math.round(ms / 1000));
  if (s < 5) return 'now';
  if (s < 60) return `${s}s`;
  const m = Math.round(s / 60);
  if (m < 60) return `${m}m`;
  const h = Math.round(m / 60);
  if (h < 48) return `${h}h`;
  return `${Math.round(h / 24)}d`;
}
